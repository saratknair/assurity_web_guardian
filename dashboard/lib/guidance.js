// Pure Automated_Guidance helpers. No window/document at import time.
//
// isGenericGuidance RULE (Requirement 7.5). src/publish/guidance.ts (task 6.1)
// MUST mirror this exactly; a cross-test compares both implementations.
//
//   1. A value that is not a string is generic.
//   2. Normalize: replace every run of whitespace with one space, trim,
//      lowercase.
//   3. The empty string is generic.
//   4. Remove ONE parenthesized quoted detail of the form  ("...")  (the
//      first `("` up to the LAST `")` in the text, greedy, may be empty)
//      together with the single space before it, if present.
//   5. Remove one leading "likely impact:" prefix and the spaces after it.
//   6. Remove trailing "." characters and trim.
//   7. The text is generic if and only if the result equals one of
//      GENERIC_GUIDANCE_CORES exactly.
//
// This covers the legacy templates from src/agents/ai-agents.ts:
//   Likely impact: a failing deterministic check ("...") may affect users; recommend human review.
//   Observed change ("...") is not a deterministic failure; a human should decide if it matters.
//   The current screenshot differs visually from the baseline. This may be a layout or content
//   change; a human should confirm whether it is expected.
// and the bare sentence quoted in Requirement 7.5.

export const GENERIC_GUIDANCE_CORES = Object.freeze([
  "a failing deterministic check may affect users; recommend human review",
  "observed change is not a deterministic failure; a human should decide if it matters",
  "the current screenshot differs visually from the baseline. this may be a layout or content change; a human should confirm whether it is expected",
]);

/** True when the text carries no more information than a generic template. */
export function isGenericGuidance(text) {
  if (typeof text !== "string") return true;
  let t = text.replace(/\s+/g, " ").trim().toLowerCase();
  if (t === "") return true;
  const open = t.indexOf('("');
  const close = t.lastIndexOf('")');
  if (open !== -1 && close !== -1 && close >= open) {
    const start = open > 0 && t.charAt(open - 1) === " " ? open - 1 : open;
    t = t.slice(0, start) + t.slice(close + 2);
  }
  if (t.indexOf("likely impact:") === 0) t = t.slice("likely impact:".length).replace(/^ +/, "");
  t = t.replace(/\.+$/, "").trim();
  return GENERIC_GUIDANCE_CORES.indexOf(t) !== -1;
}

function isObj(v) {
  return v !== null && typeof v === "object" && !Array.isArray(v);
}

/** Build a membership test from a Map, Set, plain object, or array of findings/ids. */
function idLookup(findingsById) {
  if (findingsById instanceof Map) return (id) => findingsById.has(id);
  if (findingsById instanceof Set) return (id) => findingsById.has(id);
  if (Array.isArray(findingsById)) {
    const ids = new Set();
    for (const f of findingsById) {
      if (typeof f === "string") ids.add(f);
      else if (isObj(f) && typeof f.id === "string") ids.add(f.id);
    }
    return (id) => ids.has(id);
  }
  if (isObj(findingsById)) {
    return (id) => Object.prototype.hasOwnProperty.call(findingsById, id);
  }
  return () => false;
}

/**
 * Items that may be displayed (Requirements 7.5, 7.8, 7.9):
 *  - drops items whose `findingId` is not a Finding of the run,
 *  - drops items whose `text` is generic (isGenericGuidance),
 *  - returns shallow copies with every `confidence*` field removed.
 * Input order is preserved. Never throws.
 */
export function visibleGuidance(items, findingsById) {
  const has = idLookup(findingsById);
  const out = [];
  for (const item of Array.isArray(items) ? items : []) {
    if (!isObj(item)) continue;
    if (typeof item.findingId !== "string" || item.findingId === "" || !has(item.findingId)) continue;
    if (isGenericGuidance(item.text)) continue;
    const copy = {};
    for (const k of Object.keys(item)) {
      if (/^confidence/i.test(k)) continue;
      copy[k] = item[k];
    }
    out.push(copy);
  }
  return out;
}

